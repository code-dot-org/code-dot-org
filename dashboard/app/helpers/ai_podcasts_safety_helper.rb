require 'cdo/aws/metrics'

# Detects toxicity in AI-generated podcast script content. Deliberately mirrors
# AichatSafetyHelper rather than extending it so we can iterate on podcast
# moderation without risk to the chat path running in production. Plan to
# consolidate once the podcast prompt and the chat prompt have both stabilized.
module AiPodcastsSafetyHelper
  MODEL = SharedConstants::AICHAT_MODEL_VERSION

  class ToxicityDetector
    VALID_EVALUATION_RESPONSES_SIMPLE = ['INAPPROPRIATE', 'OK']

    # Returns {text: input (string), blocked_by: serviced that detected toxicity (string), details: filtering details (hash)}
    # We currently use OpenAI for content moderation.
    def find_toxicity(text, role)
      details = openai_safety_check(text, role)
      {text: text, blocked_by: 'openai', details: details} if details
    end

    private def openai_safety_check(text, role)
      details = nil
      start_time = Time.now
      report_openai_safety_check("Start")
      attempts = 0
      input = safety_check_input(text)
      output_type = 'Unstructured'
      safety_read_timeout = DCDO.get('ai_podcasts_safety_openai_read_timeout', DCDO.get('openai_http_read_timeout', 20))

      response = Retryable.retryable(
        tries: 2,
        on: [Net::OpenTimeout, Net::ReadTimeout, SocketError, Errno::ECONNRESET]
      ) do
        attempts += 1
        start_time_unstructured = Time.now
        begin
          client.request_chat_completion(input, 1, read_timeout: safety_read_timeout)
        ensure
          duration = Time.now - start_time_unstructured
          report_detailed_latency(duration, output_type, role)
        end
      end
      raise "OpenAI request failed with status #{response.code}: #{response.body}" unless response.success?

      body = JSON.parse(response.body)
      token_count = body.dig('usage', 'output_tokens') || 0
      report_token_usage(token_count, output_type, role)

      evaluation = body.dig("output", 0, "content", 0, "text")
      unless VALID_EVALUATION_RESPONSES_SIMPLE.include?(evaluation)
        report_openai_safety_check("InvalidResponse", attempts, output_type, role)
        output_type = 'Structured'
        attempts += 1

        start_time_structured = Time.now
        begin
          response = client.request_chat_completion(input, 0, options: {text: structured_response_format}, read_timeout: safety_read_timeout)
        ensure
          duration = Time.now - start_time_structured
          report_detailed_latency(duration, output_type, role)
        end

        raise "OpenAI structured request failed with status #{response.code}: #{response.body}" unless response.success?

        body = JSON.parse(response.body)
        token_count = body.dig('usage', 'output_tokens') || 0
        report_token_usage(token_count, output_type, role)

        raw_content = body.dig("output", 0, "content", 0, "text")

        begin
          parsed = JSON.parse(raw_content)
        rescue JSON::ParserError
          report_openai_safety_check("InvalidResponse", attempts, output_type, role)
          raise "Structured response was not valid JSON: #{raw_content}"
        end

        evaluation = parsed["classification"]

        unless VALID_EVALUATION_RESPONSES_SIMPLE.include?(evaluation)
          report_openai_safety_check("InvalidResponse", attempts, output_type, role)
          raise "Unexpected structured classification from OpenAI: #{evaluation}"
        end
      end

      if evaluation == 'INAPPROPRIATE'
        report_toxicity_detected(output_type, role)
        details = {evaluation: evaluation}
      end

      report_openai_safety_check("Finish", attempts)
      latency = Time.now - start_time
      report_openai_safety_latency(latency, attempts)
      details
    end

    private def client
      AichatOpenaiResponsesHelper::Client.new(CDO.openai_student_learning_api_key, MODEL)
    end

    private def get_safety_system_prompt
      "You are a content filter trying to prevent inappropriate content from reaching students in an American middle school classroom (ages 12-16). You are reviewing conversational podcasts generated by AI and sorting them based on whether or not they contain inappropriate content. Examples of inappropriate content: profanity, swears, illegal behavior, insults, bullying, slurs, sex, violence, racism, sexism, threats, weapons, dirty slang, drinking, references to alcohol or drunkenness, drug use, etc. Review the following podcast script. If the script is inappropriate, respond with the single word `INAPPROPRIATE`, otherwise respond with the single word `OK`."
    end

    private def get_safety_system_prompt_version
      'V0'
    end

    private def safety_check_input(text)
      [
        {
          role: "system",
          content: [{type: 'input_text', text: get_safety_system_prompt}]
        },
        {
          role: "user",
          content: [{type: 'input_text', text: text}]
        }
      ]
    end

    private def structured_response_format
      {
        format: {
          name: "safety_evaluation",
          type: "json_schema",
          schema: {
            type: "object",
            properties: {
              classification: {
                type: "string",
                description: "Safety classification for school appropriateness",
                enum: ["OK", "INAPPROPRIATE"]
              }
            },
            required: ["classification"],
            additionalProperties: false
          }
        }
      }
    end

    private def report_openai_safety_check(metric_name, num_attempts = 1, output_type = nil, role = nil)
      return unless CDO.rack_env
      safety_dimensions = [
        {name: 'Environment', value: CDO.rack_env},
        {name: 'PromptVersion', value: get_safety_system_prompt_version},
      ]
      safety_dimensions << {name: 'OutputType', value: output_type} if output_type
      safety_dimensions << {name: 'Role', value: role} if role
      if metric_name == 'Finish'
        safety_dimensions << {name: 'Attempts', value: num_attempts.to_s}
      end
      Cdo::Metrics.push(SharedConstants::AICHAT_METRICS_NAMESPACE,
        [
          {
            metric_name: "AiPodcastsSafety.Openai.#{metric_name}",
            value: 1,
            unit: 'Count',
            timestamp: Time.now,
            dimensions: safety_dimensions
          }
        ]
      )
    end

    private def report_openai_safety_latency(latency, num_attempts)
      return unless CDO.rack_env
      Cdo::Metrics.push(SharedConstants::AICHAT_METRICS_NAMESPACE,
        [
          {
            metric_name: "AiPodcastsSafety.Openai.Latency",
            value: latency,
            unit: 'Seconds',
            timestamp: Time.now,
            dimensions: [
              {name: 'Environment', value: CDO.rack_env},
              {name: 'PromptVersion', value: get_safety_system_prompt_version},
              {name: 'Attempts', value: num_attempts.to_s},
            ]
          }
        ]
      )
    end

    private def report_detailed_latency(latency, output_type, role)
      return unless CDO.rack_env
      Cdo::Metrics.push(SharedConstants::AICHAT_METRICS_NAMESPACE,
        [
          {
            metric_name: "AiPodcastsSafety.Openai.Latency.Detailed",
            value: latency,
            unit: 'Seconds',
            timestamp: Time.now,
            dimensions: [
              {name: 'Environment', value: CDO.rack_env},
              {name: 'OutputType', value: output_type},
              {name: 'Role', value: role},
            ]
          }
        ]
      )
    end

    private def report_token_usage(count, output_type, role)
      return unless CDO.rack_env
      Cdo::Metrics.push(SharedConstants::AICHAT_METRICS_NAMESPACE,
        [
          {
            metric_name: "AiPodcastsSafety.Openai.CompletionTokens",
            value: count,
            unit: 'Count',
            timestamp: Time.now,
            dimensions: [
              {name: 'Environment', value: CDO.rack_env},
              {name: 'OutputType', value: output_type},
              {name: 'Role', value: role},
            ]
          }
        ]
      )
    end

    private def report_toxicity_detected(output_type, role)
      return unless CDO.rack_env
      Cdo::Metrics.push(SharedConstants::AICHAT_METRICS_NAMESPACE,
        [
          {
            metric_name: "AiPodcastsSafety.Openai.ToxicityDetected",
            value: 1,
            unit: 'Count',
            timestamp: Time.now,
            dimensions: [
              {name: 'Environment', value: CDO.rack_env},
              {name: 'OutputType', value: output_type},
              {name: 'Role', value: role},
            ]
          }
        ]
      )
    end
  end

  class StubbedToxicityDetector
    def find_toxicity(text, _)
      # UI tests use the literal word "Damn" to exercise the inappropriate-content
      # branch without a roundtrip to the moderation service. Matches the
      # convention in AichatSafetyHelper::StubbedToxicityDetector.
      text == 'Damn' ?
        {text: text, blocked_by: 'openai', details: {evaluation: 'INAPPROPRIATE'}} :
        nil
    end
  end

  def self.find_toxicity(text, role = 'Model')
    Rails.application.config.respond_to?(:stub_aichat_external_services) && Rails.application.config.stub_aichat_external_services ?
      StubbedToxicityDetector.new.find_toxicity(text, nil) :
      ToxicityDetector.new.find_toxicity(text, role)
  end
end
