module AiSystemPrompts::EvaluateSystemPromptHelper
  def self.get_system_prompt(level, evaluation_type)
    evaluation_criteria = get_evaluation_criteria(level)
    evaluation_summary = get_evaluation_criteria_summary(level)
    skill_evaluations = get_skill_evaluations(level)
    skills = level.skills
    variable_skill_levels = [{
      skillId: 2,
      skillKey: 'variables_declare',
      evaluationCriteria: ['Beginning: Variables are missing or contain syntax errors (example: missing var, invalid characters)', 'Approaching: Some variables declared correctly, some with syntax errors', 'Developing: Declares variables with var and mostly correct syntax', 'Meeting/Exceeding: Declares all variables using var with clear, valid names']
    },
    {
      skillId: 4,
      skillKey: 'variables_name',
      evaluationCriteria: ['Beginning: Uses unclear or inconsistent names (example:  x1, abc)', 'Approaching: Some names are meaningful, but inconsistently', 'Developing: Most variable names are descriptive and consistent', 'Meeting/Exceeding: All variable names are clear, descriptive, and consistent']
    }]
    structure_with_skills = <<~TEXT
      Your task is to review the student's work. Respond in correctly formatted JSON\n
      evaluationCriteria should be a copy of #{evaluation_summary}.\n
      aiReasoning should consist of the following numbered parts: 1. Compare the student code to the starter code and create a bulleted list of each line that has been changed, added, or removed, 2. Create a bulleted list of all lines of code from part 1 that are relevant to assessing the student's work, 3. Provide a step-by-step analysis of the lines of code listed in part 2, explaining how each line is relevant to assessing the quality of the student's work.\n
      aiEvaluation should be your overall assessment of the student's work based on the information in aiReasoning. Respond with #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:ALL_COMPLETE_CORRECT]} if the student's work meets all expectations, #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:PARTIAL_COMPLETE_CORRECT]} if it meets some, and #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:INCOMPLETE_INCORRECT]} if it is incorrect or incomplete.\n
      skillEvaluations should be an array of objects based on #{variable_skill_levels} with the following structure: {skillId: skillId, skillKey: skillKey, evaluationCriteria: evaluationCriteria, aiReasoning: aiReasoning should consist of the following numbered parts: 1. Compare the student code to the starter code and create a bulleted list of each line that has been changed, added, or removed, 2. Create a bulleted list of all lines of code from part 1 that are relevant to the evaluationCriteria, 3. Provide a step-by-step analysis of the lines of code listed in part 2, explaining how each line is relevant to assessing the evaluationCriteria, 4. Explain how the student met or failed to meet each level in the evaluationCriteria based on its associated criteria, aiEvaluation: Respond with your overall assessment of which level the student achieved based on the information in aiReasoning. Respond with Beginning, Approaching, Developing, or Meeting/Exceeding based on the evaluationCriteria} generated by iterating through the skills.\n
    TEXT
    structure_without_skills = <<~TEXT
      Your task is to review the student's work. Respond in correctly formatted JSON.
      evaluationCriteria should be a copy of #{evaluation_criteria}.
      aiEvaluation should be your overall assessment of the student's work. Respond with #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:INCOMPLETE_INCORRECT]} if the student's answer is unrelated (e.g. “idk”, “I don't know”, "who cares", or "na"), off-topic. Respond with #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:INCOMPLETE_INCORRECT]} if the student's answer incorrectly answers the questions asked in the level instructions. Respond with #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:ALL_COMPLETE_CORRECT]} if the student's answer accurately answers all parts of the questions asked or directions given in the level instructions. Respond with #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:PARTIAL_COMPLETE_CORRECT]} if the student's work partially meets the requirements of the level instructions.
      aiReasoning should be one sentence with your reasoning.
    TEXT
    single_student_evaluation_structure = skills.empty? ? structure_without_skills : structure_with_skills
    evaluation_structure = evaluation_type == SharedConstants::AI_EVALUATION_TYPES[:SINGLE_STUDENT] ? single_student_evaluation_structure : section_summary_evaluation_structure
    prompt = AiSystemPrompts::SystemPromptHelper.get_basic_system_prompt(level)
    prompt << evaluation_structure
  end

  def self.get_evaluation_criteria_summary(level)
    skills = level.skills
    summary = "Evaluated for completion based on a level instructions."
    if skills.empty? && level.upper_grades_programming_level?
      summary << "\n Evaluated for general code quality."
    elsif skills.any?
      summary << "\n Evaluated for #{skills.length} skills."
    end
    summary
  end

  def self.get_skill_evaluations(level)
    skills = level.skills
    skill_evaluations = []
    if skills.any?
      skills.each do |skill|
        skill_evaluations << {
          skillKey: skill.key,
          evaluationCriteria: skill.evaluation_criteria
        }
      end
    end
    skill_evaluations
  end

  def self.get_evaluation_criteria(level)
    completion_criteria = "Did the student complete all of the requirements in the instructions?"
    evaluation_criteria = [completion_criteria]
    skills = level.skills
    if skills.any?
      skills.each do |skill|
        evaluation_criteria << skill.evaluation_criteria
      end
    elsif level.upper_grades_programming_level?
      code_quality_criteria = "Does the code run without errors? Does the code follow best practices?"
      evaluation_criteria << code_quality_criteria
    end
    evaluation_criteria
  end
end
