module AiSystemPrompts::EvaluateSystemPromptHelper
  def self.get_system_prompt(level, evaluation_type)
    additional_directions = level.respond_to?(:additional_ai_evaluation_instructions) && level.additional_ai_evaluation_instructions.present? ? level.additional_ai_evaluation_instructions.strip + "\n" : ''
    evaluation_criteria = get_evaluation_criteria(level)
    task_context = "Your task is to review the student's work."
    if additional_directions.present?
      task_context << " #{additional_directions}"
    end
    skill_evaluations = get_skill_evaluations(level)
    skills = level.skills
    structure_with_skills = if level.upper_grades_programming_level?
      <<~TEXT
        #{task_context} Respond in correctly formatted JSON
        In your review, you will generate a skill evaluation for each skill in the following list:
        #{skill_evaluations}#{' '}
        For each skill evaluation, you will assess how well the student demonstrates the listed skill in their code by giving them a rating from the following list: #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:ALL_COMPLETE_CORRECT]} if the student's work demonstrated the skill consistently and completely, #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:PARTIAL_COMPLETE_CORRECT]} if it demonstrates the skill partially or inconsistently, and #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:INCOMPLETE_INCORRECT]} if it does not show evidence of the skill or shows a misunderstanding. You will also provide a reason explaining your rating for each skill, citing examples from the code to support your decision.
        Provide your response in an array with an entry for each skill evaluation. Each skill evaluation must be provided in correctly formatted JSON with the following structure:
        skillId: skillId,
        skillKey: skillKey,
        evaluationCriteria: evaluationCriteria,
        aiReasoning: Should consist of the following two parts: 1. Create a bulleted list of each specific line of code in the student's work that differs from the starter code. Include the line number and the change that was made. This should include all lines that have been changed, added, or removed. 2. Provide a step-by-step analysis of each line of code listed in part 1, explaining how each line is relevant to assessing the evaluationCriteria,
        aiEvaluation: Respond with your overall assessment of the student's work based on the information in aiReasoning. Respond with #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:ALL_COMPLETE_CORRECT]} if the student's work demonstrated the skill consistently and completely, #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:PARTIAL_COMPLETE_CORRECT]} if it demonstrates the skill partially or inconsistently, and #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:INCOMPLETE_INCORRECT]} if it does not show evidence of the skill or shows a misunderstanding. generated by iterating through the skills.\n
      TEXT
    end
    structure_without_skills = <<~TEXT
      #{task_context} Respond in correctly formatted JSON.
      evaluationCriteria should be a copy of #{evaluation_criteria}.
      aiEvaluation should be your overall assessment of the student's work. Respond with #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:INCOMPLETE_INCORRECT]} if the student's answer is unrelated (e.g. “idk”, “I don't know”, "who cares", or "na"), off-topic. Respond with #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:INCOMPLETE_INCORRECT]} if the student's answer incorrectly answers the questions asked in the level instructions. Respond with #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:ALL_COMPLETE_CORRECT]} if the student's answer accurately answers all parts of the questions asked or directions given in the level instructions. Respond with #{SharedConstants::STUDENT_WORK_EVALUATION_STATUS[:PARTIAL_COMPLETE_CORRECT]} if the student's work partially meets the requirements of the level instructions.
      aiReasoning should be one sentence with your reasoning.
    TEXT
    single_student_evaluation_structure = skills.empty? ? structure_without_skills : structure_with_skills
    evaluation_structure = evaluation_type == SharedConstants::AI_EVALUATION_TYPES[:SINGLE_STUDENT] ? single_student_evaluation_structure : section_summary_evaluation_structure
    prompt = AiSystemPrompts::SystemPromptHelper.get_basic_system_prompt(level)
    prompt << evaluation_structure
  end

  def self.get_skill_evaluations(level)
    skills = level.skills
    skill_evaluations = []
    if skills.any?
      skills.each do |skill|
        skill_evaluations << {
          skillKey: skill.key,
          evaluationCriteria: skill.evaluation_criteria
        }
      end
    end
    skill_evaluations
  end

  def self.get_evaluation_criteria(level)
    completion_criteria = "Did the student complete all of the requirements in the instructions?"
    evaluation_criteria = [completion_criteria]
    skills = level.skills
    if skills.any?
      skills.each do |skill|
        evaluation_criteria << skill.evaluation_criteria
      end
    elsif level.upper_grades_programming_level?
      code_quality_criteria = "Does the code run without errors? Does the code follow best practices?"
      evaluation_criteria << code_quality_criteria
    end
    evaluation_criteria
  end
end
