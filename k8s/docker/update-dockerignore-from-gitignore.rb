#!/usr/bin/env -S bundle exec ruby
# frozen_string_literal: true

require 'open3'
require 'pathname'

SCRIPT_DIR = Pathname(__dir__).realpath
REPO_ROOT = (SCRIPT_DIR / '../..').realpath
DOCKERIGNORE_PATH = SCRIPT_DIR / 'code-dot-org.dockerfile.dockerignore'
SCRIPT_NAME = Pathname(__FILE__).basename.to_s
BEGIN_MARKER = '##### BEGIN AUTOGENERATED BY update-dockerignore-from-gitignore.rb #####'
END_MARKER = '##### END AUTOGENERATED BY update-dockerignore-from-gitignore.rb #####'
GENERATED_BLOCK_PATTERN = /#{Regexp.escape(BEGIN_MARKER)}.*#{Regexp.escape(END_MARKER)}/m

def tracked_gitignore_paths
  stdout, stderr, status = Open3.capture3(
    'git',
    'ls-files',
    '--full-name',
    '--',
    '.gitignore',
    '**/.gitignore',
    chdir: REPO_ROOT.to_s
  )
  raise "git ls-files failed:\n#{stderr}" unless status.success?

  stdout.lines.map(&:chomp)
end

def gitignore_directory(gitignore_path)
  dirname = File.dirname(gitignore_path)
  dirname == '.' ? '' : dirname
end

def convert_gitignore_pattern(gitignore_path, raw_pattern)
  negated = raw_pattern.start_with?('!')
  pattern = negated ? raw_pattern.delete_prefix('!') : raw_pattern
  anchored = pattern.start_with?('/')
  pattern = pattern.delete_prefix('/')
  base_dir = gitignore_directory(gitignore_path)

  basename_rule = !anchored && !pattern.chomp('/').include?('/')

  converted_pattern =
    if basename_rule
      base_dir.empty? ? "**/#{pattern}" : "#{base_dir}/**/#{pattern}"
    else
      prefixed_pattern = base_dir.empty? ? pattern : "#{base_dir}/#{pattern}"
      anchored ? "/#{prefixed_pattern}" : prefixed_pattern
    end

  "#{negated ? '!' : ''}#{converted_pattern}"
end

def generated_lines_for(gitignore_path)
  lines = (REPO_ROOT / gitignore_path).readlines(chomp: true)

  patterns = lines.filter_map do |line|
    next if line.empty? || line.lstrip.start_with?('#')

    convert_gitignore_pattern(gitignore_path, line)
  end

  return [] if patterns.empty?

  ["# do not edit, autogenerated from `#{gitignore_path}` by #{SCRIPT_NAME}", *patterns]
end

def build_generated_block(gitignore_paths)
  blocks = gitignore_paths.filter_map do |gitignore_path|
    lines = generated_lines_for(gitignore_path)
    next if lines.empty?

    lines.join("\n")
  end

  ([BEGIN_MARKER, '', blocks.join("\n\n"), '', END_MARKER]).join("\n")
end

def replace_generated_block(content, generated_block)
  raise "Could not find autogenerated markers in #{DOCKERIGNORE_PATH}" unless content.match?(GENERATED_BLOCK_PATTERN)

  content.sub(GENERATED_BLOCK_PATTERN, generated_block)
end

def main
  gitignore_paths = tracked_gitignore_paths
  content = DOCKERIGNORE_PATH.read
  updated = replace_generated_block(content, build_generated_block(gitignore_paths))
  DOCKERIGNORE_PATH.write(updated)

  puts "Updated #{DOCKERIGNORE_PATH.relative_path_from(REPO_ROOT)} from #{gitignore_paths.length} .gitignore files"
end

main if $PROGRAM_NAME == __FILE__
