# curriculum_urls.rb — enumerate anonymously-servable curriculum paths, WEIGHTED to
# mirror production traffic (Sentry transaction TPM).
#
# Run on any box with the seeded curriculum DB (the adhoc, or local):
#   cd dashboard && ./bin/rails runner ../bin/oneoff/curriculum_urls.rb [OUTPUT_FILE]
#
# Writes "<weight>\t<path>" lines to OUTPUT_FILE (default: ./curriculum_urls.txt), plus
# '#' comments. We write the file OURSELVES rather than relying on a '>' redirect, because
# boot-time initializers scribble on stdout (e.g. "GetSecretValue: .../slack_bot_token"),
# which would otherwise land in the output.
#
# Enumeration reads the DB directly (Unit.all / UnitGroup.all), NOT the in-process cache:
# Unit.script_cache returns nil unless should_cache?, which is false in a `rails runner`.
# The paths are identical either way; the running puma still serves them from the warmed
# cache, so every 200 the load driver gets reads a pre-warmed, old-gen object, not the DB.
#
# Weighting rationale (from Sentry, requests/min, mapped to the warmed objects each reads):
#   script_levels#show  — the warmed ScriptLevel/Level cache. We fold in milestone
#                         (6.59/min), the top curriculum reader, which reads the same
#                         objects but is a progress-writing POST we don't replay; its
#                         read volume is proxied here. Plus script_levels#show itself,
#                         normally the ~2nd-highest action (edge-cached in prod, so it's
#                         under-counted in the Rails-side Sentry view).
#   hidden_lesson_ids   — 3.36/min; reads Unit + lessons; anon GET, no writes.
#   scripts#show / units-nested / courses#show / lessons#show — heavy curriculum ALLOCATORS
#                         (full summarize); lower TPM but the biggest GC churn per request,
#                         which is what actually erodes copy-on-write sharing.
# get_rubric is omitted: it uses Level.find (DB), not the warmed level_cache.
#
# Tunables (env): weights (floats) and sampling.
W = {
  script_level: (ENV['W_SCRIPT_LEVEL'] || 7.0).to_f,   # milestone + script_levels#show
  hidden:       (ENV['W_HIDDEN']       || 3.4).to_f,
  script_show:  (ENV['W_SCRIPT_SHOW']  || 1.0).to_f,
  unit_nested:  (ENV['W_UNIT_NESTED']  || 1.0).to_f,
  lesson:       (ENV['W_LESSON']       || 1.0).to_f,
  course:       (ENV['W_COURSE']       || 1.0).to_f,
}
max_units         = (ENV['MAX_UNITS'] || 0).to_i
lessons_per_unit  = (ENV['LESSONS_PER_UNIT'] || 4).to_i
levels_per_lesson = (ENV['LEVELS_PER_LESSON'] || 3).to_i
out_path          = ARGV[0] || ENV['OUT'] || 'curriculum_urls.txt'

sample = lambda do |list, n|
  return list if n <= 0 || list.size <= n
  step = list.size.to_f / n
  (0...n).map {|i| list[(i * step).to_i]}
end

servable_unit = lambda do |unit|
  unit.launched? && !unit.login_required &&
    !(unit.respond_to?(:in_development?) && unit.in_development?) &&
    !(unit.respond_to?(:pilot?) && unit.pilot?)
rescue StandardError
  false
end

lines  = []
counts = Hash.new(0)
emit = ->(weight, path) {lines << "#{weight.round(3)}\t#{path}"}

units = Unit.all.to_a
units = units.first(max_units) if max_units > 0
units.each do |unit|
  next unless servable_unit.call(unit)
  emit.call(W[:script_show], "/s/#{unit.name}")
  emit.call(W[:hidden],      "/s/#{unit.name}/hidden_lessons")
  counts[:units] += 1

  lessons = begin
    unit.lessons.to_a.select(&:has_lesson_plan)
  rescue StandardError
    []
  end
  sample.call(lessons, lessons_per_unit).each do |lesson|
    emit.call(W[:lesson], "/s/#{unit.name}/lessons/#{lesson.relative_position}")
    counts[:lessons] += 1

    levels = begin
      lesson.script_levels.to_a
    rescue StandardError
      []
    end
    sample.call(levels, levels_per_lesson).each do |sl|
      pos = begin
        sl.position
      rescue
        nil
      end
      next unless pos
      emit.call(W[:script_level], "/s/#{unit.name}/lessons/#{lesson.relative_position}/levels/#{pos}")
      counts[:levels] += 1
    end
  end
rescue StandardError => exception
  warn "skip unit #{unit&.name}: #{exception.class} #{exception.message}"
end

UnitGroup.all.to_a.each do |ug|
  launched = begin
    ug.launched?
  rescue
    true
  end
  next unless launched && !(ug.respond_to?(:login_required) && ug.login_required)
  emit.call(W[:course], "/courses/#{ug.name}")
  counts[:courses] += 1
  nested = begin
    ug.default_units.to_a
  rescue
    []
  end
  nested.each_with_index do |_unit, i|
    emit.call(W[:unit_nested], "/courses/#{ug.name}/units/#{i + 1}")
    counts[:units_nested] += 1
  end
rescue StandardError => exception
  warn "skip course #{ug&.name}: #{exception.class} #{exception.message}"
end

File.open(out_path, 'w') do |f|
  f.puts "# generated by curriculum_urls.rb  (format: <weight>\\t<path>)"
  f.puts "# weights: #{W.map {|k, v| "#{k}=#{v}"}.join(' ')}"
  f.puts "# counts:  units=#{counts[:units]} lessons=#{counts[:lessons]} levels=#{counts[:levels]} courses=#{counts[:courses]} units_nested=#{counts[:units_nested]} total_lines=#{lines.size}"
  f.puts lines
end
warn "wrote #{lines.size} weighted paths to #{out_path} (#{counts.map {|k, v| "#{k}=#{v}"}.join(' ')})"
