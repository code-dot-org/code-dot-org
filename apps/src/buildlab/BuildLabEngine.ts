import {
  compileBuildLabWorkspace,
  type BuildlabWorkspaceState,
} from './buildlabBlockly';
import {
  normalizeSpriteDataKey,
  SPRITE_PREDICTION_DATA_KEYS,
  type Asset,
  type StageElement,
  type StageScreen,
} from './project';
import {
  clampToStage,
  DEFAULT_SPRITE_SIZE,
  moveWithArrowKeys,
  spritesAreTouching,
  STAGE_SIZE,
  type ArrowDirection,
  type PendingGeneration,
  type PendingPrediction,
  type RuntimeAnimation,
  type RuntimeState,
} from './runtime';

const GRID_SIZE = 5;
const DEFAULT_ANIMATION_FPS = 8;

export interface BuildLabEngineOptions {
  assets?: Asset[];
  fallbackSpriteAssetId?: string;
  initialState: RuntimeState;
  screens: StageScreen[];
}

type RuntimeHandler = () => void;

interface TouchRegistration {
  firstId: string;
  handlers: RuntimeHandler[];
  targetSelector: string;
}

/**
 * Executes the JavaScript generated by the Build Lab Blockly workspace.
 *
 * The engine owns runtime state and event registration. React renders the
 * returned state, but does not interpret block types itself. This is the same
 * boundary used by Lab2 engines: Blockly generates a program, and the engine
 * exposes the runtime API that program is allowed to call.
 */
export default class BuildLabEngine {
  private readonly assets: Asset[];
  private readonly fallbackSpriteAssetId?: string;
  private readonly initialState: RuntimeState;
  private readonly screens: StageScreen[];
  private state: RuntimeState;
  private startHandlers: RuntimeHandler[] = [];
  private clickHandlers = new Map<string, RuntimeHandler[]>();
  private touchHandlers = new Map<string, TouchRegistration>();
  private activeTouchPairs = new Set<string>();
  private variableBindings = new Map<string, string>();
  private predictionReadyHandlers = new Map<string, RuntimeHandler[]>();
  private predictionFailedHandlers = new Map<string, RuntimeHandler[]>();
  private pendingPredictions: PendingPrediction[] = [];
  private latestPredictionRequests = new Map<string, number>();
  private nextPredictionRequestId = 1;
  private activeTouchTargetId?: string;
  private pendingGenerations: PendingGeneration[] = [];
  private activeGenerationRequests = new Set<number>();
  private latestGenerationRequests = new Map<string, number>();
  private nextGenerationRequestId = 1;
  private generatingAnimations = new Map<string, string>();
  private generationAnimationSnapshots = new Map<
    string,
    RuntimeAnimation | undefined
  >();

  public constructor({
    assets = [],
    fallbackSpriteAssetId,
    initialState,
    screens,
  }: BuildLabEngineOptions) {
    this.assets = assets;
    this.fallbackSpriteAssetId = fallbackSpriteAssetId;
    this.initialState = cloneRuntimeState(initialState);
    this.screens = screens;
    this.state = cloneRuntimeState(initialState);
  }

  public run(workspaceState: BuildlabWorkspaceState): RuntimeState {
    this.state = {
      ...cloneRuntimeState(this.initialState),
      animations: {},
      keyboardMovements: [],
      variables: {},
      pendingGeneration: undefined,
      pendingPrediction: undefined,
    };
    this.startHandlers = [];
    this.clickHandlers.clear();
    this.touchHandlers.clear();
    this.activeTouchPairs.clear();
    this.variableBindings.clear();
    this.predictionReadyHandlers.clear();
    this.predictionFailedHandlers.clear();
    this.pendingPredictions = [];
    this.latestPredictionRequests.clear();
    this.nextPredictionRequestId = 1;
    this.activeTouchTargetId = undefined;
    this.pendingGenerations = [];
    this.activeGenerationRequests.clear();
    this.latestGenerationRequests.clear();
    this.nextGenerationRequestId = 1;
    this.generatingAnimations.clear();
    this.generationAnimationSnapshots.clear();

    const source = compileBuildLabWorkspace(workspaceState);
    this.executeGeneratedProgram(source);
    for (const handler of [...this.startHandlers]) {
      handler();
    }
    this.checkTouchEvents();
    return this.getState();
  }

  public triggerClick(elementId: string): RuntimeState {
    this.clearPendingRequests();
    for (const handler of this.clickHandlers.get(elementId) ?? []) {
      handler();
    }
    this.checkTouchEvents();
    return this.getState();
  }

  public moveWithArrowKeys(
    directions: ReadonlySet<ArrowDirection>
  ): RuntimeState {
    this.state = moveWithArrowKeys(this.state, directions);
    this.checkTouchEvents();
    return this.getState();
  }

  public getState(): RuntimeState {
    return cloneRuntimeState(this.state);
  }

  public updateElement(elementId: string, changes: Partial<StageElement>) {
    this.state = {
      ...this.state,
      elements: this.state.elements.map(element =>
        element.id === elementId ? {...element, ...changes} : element
      ),
    };
  }

  public onStart(handler: RuntimeHandler) {
    this.startHandlers.push(handler);
  }

  public onClick(elementId: string, handler: RuntimeHandler) {
    const handlers = this.clickHandlers.get(elementId) ?? [];
    handlers.push(handler);
    this.clickHandlers.set(elementId, handlers);
  }

  public onPredictionReady(spriteId: string, handler: RuntimeHandler) {
    if (!this.isSprite(spriteId)) {
      return;
    }

    const handlers = this.predictionReadyHandlers.get(spriteId) ?? [];
    handlers.push(handler);
    this.predictionReadyHandlers.set(spriteId, handlers);
  }

  public onPredictionFailed(spriteId: string, handler: RuntimeHandler) {
    if (!this.isSprite(spriteId)) {
      return;
    }

    const handlers = this.predictionFailedHandlers.get(spriteId) ?? [];
    handlers.push(handler);
    this.predictionFailedHandlers.set(spriteId, handlers);
  }

  public onTouch(
    firstId: string,
    targetSelector: string,
    handler: RuntimeHandler
  ) {
    if (!firstId || !targetSelector || firstId === targetSelector) {
      return;
    }

    const key = JSON.stringify([firstId, targetSelector]);
    const registration = this.touchHandlers.get(key) ?? {
      firstId,
      handlers: [],
      targetSelector,
    };
    registration.handlers.push(handler);
    this.touchHandlers.set(key, registration);
  }

  public setText(elementId: string, text: string) {
    this.variableBindings.delete(elementId);
    this.updateElementText(elementId, String(text));
  }

  public setSpriteData(spriteId: string, rawKey: string, value: string) {
    const key = normalizeSpriteDataKey(String(rawKey));
    if (!key || !this.isSprite(spriteId)) {
      return;
    }

    this.updateElement(spriteId, {
      data: {
        ...this.getElement(spriteId)?.data,
        [key]: String(value),
      },
    });
  }

  public getSpriteData(spriteId: string, rawKey: string) {
    const key = normalizeSpriteDataKey(String(rawKey));
    const data = this.getElement(spriteId)?.data;
    return key && data && Object.prototype.hasOwnProperty.call(data, key)
      ? data[key]
      : '';
  }

  public setTextFromSpriteData(
    elementId: string,
    spriteId: string,
    rawKey: string
  ) {
    this.setText(elementId, this.getSpriteData(spriteId, rawKey));
  }

  public setVariable(name: string, value: string) {
    const normalizedName = String(name).trim();
    if (!normalizedName) {
      return;
    }

    this.state = {
      ...this.state,
      variables: {
        ...this.state.variables,
        [normalizedName]: String(value),
      },
    };
    this.refreshVariableBindings(normalizedName);
  }

  public changeVariable(name: string, rawAmount: string) {
    const normalizedName = String(name).trim();
    if (!normalizedName) {
      return;
    }

    const currentValue = Number(this.state.variables[normalizedName] ?? 0);
    const amount = Number(rawAmount);
    const nextValue =
      (Number.isFinite(currentValue) ? currentValue : 0) +
      (Number.isFinite(amount) ? amount : 0);
    this.setVariable(normalizedName, String(nextValue));
  }

  public bindTextToVariable(elementId: string, variableName: string) {
    const normalizedName = String(variableName).trim();
    if (!elementId || !normalizedName) {
      return;
    }

    this.variableBindings.set(elementId, normalizedName);
    this.updateElementText(
      elementId,
      this.state.variables[normalizedName] ?? ''
    );
  }

  public showScreen(screenId: string) {
    if (!this.screens.some(screen => screen.id === screenId)) {
      return;
    }
    this.state = {...this.state, screenId};
  }

  public setPosition(elementId: string, x: string, y: string) {
    this.state = {
      ...this.state,
      elements: this.state.elements.map(element =>
        element.id === elementId
          ? {
              ...element,
              x: snapCoordinate(Number(x), element.width),
              y: snapCoordinate(Number(y), element.height),
            }
          : element
      ),
    };
  }

  public setVisible(elementId: string, visible: string) {
    this.state = {
      ...this.state,
      elements: this.state.elements.map(element =>
        element.id === elementId
          ? {...element, visible: visible !== 'false'}
          : element
      ),
    };
  }

  public setSpriteSize(elementId: string, rawSize: string) {
    const isSprite = this.state.elements.some(
      element => element.id === elementId && element.kind === 'sprite'
    );
    if (!isSprite) {
      return;
    }

    const numericSize = Number(rawSize);
    const sizePercent = Number.isFinite(numericSize)
      ? Math.max(10, Math.min(300, numericSize))
      : 100;
    const size = Math.round((DEFAULT_SPRITE_SIZE * sizePercent) / 100);
    this.state = {
      ...this.state,
      elements: this.state.elements.map(element =>
        element.id === elementId
          ? {...element, height: size, width: size}
          : element
      ),
    };
  }

  public changeSpritePosition(
    elementId: string,
    rawDeltaX: string,
    rawDeltaY: string
  ) {
    const deltaX = Number(rawDeltaX);
    const deltaY = Number(rawDeltaY);
    this.state = {
      ...this.state,
      elements: this.state.elements.map(element =>
        element.id === elementId && element.kind === 'sprite'
          ? {
              ...element,
              x: snapCoordinate(
                element.x + (Number.isFinite(deltaX) ? deltaX : 0),
                element.width
              ),
              y: snapCoordinate(
                element.y + (Number.isFinite(deltaY) ? deltaY : 0),
                element.height
              ),
            }
          : element
      ),
    };
  }

  public enableArrowMovement(elementId: string, rawSpeed: string) {
    const isSprite = this.state.elements.some(
      element => element.id === elementId && element.kind === 'sprite'
    );
    if (!isSprite || !elementId) {
      return;
    }

    const numericSpeed = Number(rawSpeed);
    const speed = Number.isFinite(numericSpeed)
      ? Math.max(1, Math.min(20, numericSpeed))
      : 5;
    this.state = {
      ...this.state,
      keyboardMovements: [
        ...(this.state.keyboardMovements ?? []).filter(
          movement => movement.elementId !== elementId
        ),
        {elementId, speed},
      ],
    };
  }

  public playAnimation(spriteId: string, animationAssetId: string) {
    const animationAsset = this.getAnimationAsset(animationAssetId);
    if (!this.isSprite(spriteId) || !animationAsset) {
      return;
    }

    const frameCount = animationAsset.frames?.length ?? 0;
    this.state = {
      ...this.state,
      animations: {
        ...this.state.animations,
        [spriteId]: {
          assetId: animationAssetId,
          frameIndex: 0,
          frameIntervalMs: 1000 / DEFAULT_ANIMATION_FPS,
          playing: frameCount > 1,
        },
      },
    };
  }

  public stopAnimation(spriteId: string) {
    const animation = this.state.animations?.[spriteId];
    if (!animation?.playing) {
      return;
    }

    this.state = {
      ...this.state,
      animations: {
        ...this.state.animations,
        [spriteId]: {...animation, playing: false},
      },
    };
  }

  public animateWhileGenerating(spriteId: string, animationAssetId: string) {
    if (!this.isSprite(spriteId) || !this.getAnimationAsset(animationAssetId)) {
      return;
    }

    this.generatingAnimations.set(spriteId, animationAssetId);
    if (this.activeGenerationRequests.size > 0) {
      this.startGeneratingAnimation(spriteId, animationAssetId);
    }
  }

  public advanceAnimations(timestamp: number): RuntimeState | undefined {
    const animations = this.state.animations ?? {};
    let stateChanged = false;
    let visibleFrameChanged = false;
    const nextAnimations = Object.fromEntries(
      Object.entries(animations).map(([spriteId, animation]) => {
        if (!animation.playing) {
          return [spriteId, animation];
        }

        if (animation.lastFrameTime === undefined) {
          stateChanged = true;
          return [spriteId, {...animation, lastFrameTime: timestamp}];
        }

        const elapsed = timestamp - animation.lastFrameTime;
        const elapsedFrames = Math.floor(elapsed / animation.frameIntervalMs);
        if (elapsedFrames < 1) {
          return [spriteId, animation];
        }

        const frameCount =
          this.getAnimationAsset(animation.assetId)?.frames?.length ?? 0;
        if (frameCount < 2) {
          stateChanged = true;
          return [spriteId, {...animation, playing: false}];
        }

        stateChanged = true;
        visibleFrameChanged = true;
        return [
          spriteId,
          {
            ...animation,
            frameIndex: (animation.frameIndex + elapsedFrames) % frameCount,
            lastFrameTime:
              animation.lastFrameTime +
              elapsedFrames * animation.frameIntervalMs,
          },
        ];
      })
    );

    if (!stateChanged) {
      return undefined;
    }

    this.state = {...this.state, animations: nextAnimations};
    return visibleFrameChanged ? this.getState() : undefined;
  }

  public predictModel(modelId: string, resultElementId: string) {
    if (!modelId || !resultElementId) {
      return;
    }

    const request: PendingPrediction = {
      kind: 'element',
      modelId,
      requestId: this.nextPredictionRequestId++,
      resultElementId,
    };
    this.queuePrediction(request, resultElementId);
  }

  public predictSprite(
    predictorSpriteId: string,
    modelId: string,
    sourceSpriteId: string
  ) {
    if (!modelId || !this.isSprite(predictorSpriteId)) {
      return;
    }

    const sourceSprite = this.resolvePredictionSource(sourceSpriteId);
    if (!sourceSprite) {
      this.setSpritePredictionFailure(
        predictorSpriteId,
        sourceSpriteId.startsWith('class:')
          ? 'A class data source must match the sprite in the current touch event'
          : 'Prediction source sprite not found'
      );
      return;
    }

    const request: PendingPrediction = {
      featureValues: {...sourceSprite.data},
      kind: 'sprite',
      modelId,
      predictorSpriteId,
      requestId: this.nextPredictionRequestId++,
      sourceSpriteId: sourceSprite.id,
    };
    this.setSpriteData(
      predictorSpriteId,
      SPRITE_PREDICTION_DATA_KEYS.status,
      'pending'
    );
    this.setSpriteData(
      predictorSpriteId,
      SPRITE_PREDICTION_DATA_KEYS.error,
      ''
    );
    this.setSpriteData(
      predictorSpriteId,
      SPRITE_PREDICTION_DATA_KEYS.result,
      ''
    );
    this.queuePrediction(request, predictorSpriteId);
  }

  public takePendingPredictions(): PendingPrediction[] {
    const requests = this.pendingPredictions;
    this.pendingPredictions = [];
    this.state = {...this.state, pendingPrediction: undefined};
    return requests;
  }

  public completePrediction(
    request: PendingPrediction,
    prediction: number | string
  ): RuntimeState {
    if (!this.isLatestPrediction(request)) {
      return this.getState();
    }

    this.latestPredictionRequests.delete(this.predictionTarget(request));
    if (request.kind === 'element') {
      this.updateElementText(request.resultElementId, String(prediction));
      return this.getState();
    }

    this.setSpriteData(
      request.predictorSpriteId,
      SPRITE_PREDICTION_DATA_KEYS.result,
      String(prediction)
    );
    this.setSpriteData(
      request.predictorSpriteId,
      SPRITE_PREDICTION_DATA_KEYS.status,
      'ready'
    );
    this.setSpriteData(
      request.predictorSpriteId,
      SPRITE_PREDICTION_DATA_KEYS.error,
      ''
    );
    for (const handler of [
      ...(this.predictionReadyHandlers.get(request.predictorSpriteId) ?? []),
    ]) {
      handler();
    }
    this.checkTouchEvents();
    return this.getState();
  }

  public failPrediction(
    request: PendingPrediction,
    message: string
  ): RuntimeState {
    if (!this.isLatestPrediction(request)) {
      return this.getState();
    }

    this.latestPredictionRequests.delete(this.predictionTarget(request));
    if (request.kind === 'element') {
      this.updateElementText(
        request.resultElementId,
        `Prediction failed: ${message}`
      );
    } else {
      this.setSpritePredictionFailure(request.predictorSpriteId, message);
    }
    return this.getState();
  }

  public generateText(prompt: string, resultElementId: string) {
    const trimmedPrompt = String(prompt).trim();
    if (!trimmedPrompt || !resultElementId) {
      return;
    }
    const request = {
      prompt: trimmedPrompt,
      requestId: this.nextGenerationRequestId++,
      resultElementId,
    };
    const wasGenerating = this.activeGenerationRequests.size > 0;
    this.pendingGenerations.push(request);
    this.activeGenerationRequests.add(request.requestId);
    this.latestGenerationRequests.set(resultElementId, request.requestId);
    this.state = {...this.state, pendingGeneration: request};
    if (!wasGenerating) {
      this.startGeneratingAnimations();
    }
  }

  public takePendingGenerations(): PendingGeneration[] {
    const pendingGenerations = this.pendingGenerations;
    this.pendingGenerations = [];
    this.state = {...this.state, pendingGeneration: undefined};
    return pendingGenerations;
  }

  public completeGeneration(
    request: PendingGeneration,
    response: string
  ): RuntimeState {
    if (this.isLatestGeneration(request)) {
      this.updateElementText(request.resultElementId, response);
      this.latestGenerationRequests.delete(request.resultElementId);
    }
    this.finishGeneration(request);
    return this.getState();
  }

  public failGeneration(
    request: PendingGeneration,
    message: string
  ): RuntimeState {
    if (this.isLatestGeneration(request)) {
      this.updateElementText(request.resultElementId, `AI failed: ${message}`);
      this.latestGenerationRequests.delete(request.resultElementId);
    }
    this.finishGeneration(request);
    return this.getState();
  }

  public createSprite(
    blockId: string,
    assetId: string,
    rawX: string,
    rawY: string
  ) {
    const spriteId = `runtime-sprite-${blockId}`;
    if (this.state.elements.some(element => element.id === spriteId)) {
      return;
    }

    const nextSprite: StageElement = {
      assetId: assetId || this.fallbackSpriteAssetId,
      id: spriteId,
      kind: 'sprite',
      label: 'Sprite',
      screenId: this.state.screenId,
      x: snapCoordinate(Number(rawX)),
      y: snapCoordinate(Number(rawY)),
    };
    this.state = {
      ...this.state,
      elements: [...this.state.elements, nextSprite],
    };
  }

  private clearPendingRequests() {
    this.pendingPredictions = [];
    for (const request of this.pendingGenerations) {
      this.activeGenerationRequests.delete(request.requestId);
      if (this.isLatestGeneration(request)) {
        this.latestGenerationRequests.delete(request.resultElementId);
      }
    }
    this.pendingGenerations = [];
    this.state = {
      ...this.state,
      pendingGeneration: undefined,
      pendingPrediction: undefined,
    };
    if (this.activeGenerationRequests.size === 0) {
      this.restoreGeneratingAnimations();
    }
  }

  private getElement(elementId: string) {
    return this.state.elements.find(element => element.id === elementId);
  }

  private getAnimationAsset(assetId: string) {
    return this.assets.find(
      asset =>
        asset.id === assetId &&
        asset.assetType === 'animation' &&
        Boolean(asset.frames?.length)
    );
  }

  private isLatestGeneration(request: PendingGeneration) {
    return (
      this.latestGenerationRequests.get(request.resultElementId) ===
      request.requestId
    );
  }

  private finishGeneration(request: PendingGeneration) {
    this.activeGenerationRequests.delete(request.requestId);
    if (this.activeGenerationRequests.size === 0) {
      this.restoreGeneratingAnimations();
    }
  }

  private startGeneratingAnimations() {
    for (const [spriteId, animationAssetId] of this.generatingAnimations) {
      this.startGeneratingAnimation(spriteId, animationAssetId);
    }
  }

  private startGeneratingAnimation(spriteId: string, animationAssetId: string) {
    if (!this.generationAnimationSnapshots.has(spriteId)) {
      const currentAnimation = this.state.animations?.[spriteId];
      this.generationAnimationSnapshots.set(
        spriteId,
        currentAnimation ? {...currentAnimation} : undefined
      );
    }
    this.playAnimation(spriteId, animationAssetId);
  }

  private restoreGeneratingAnimations() {
    if (this.generationAnimationSnapshots.size === 0) {
      return;
    }

    const animations = {...this.state.animations};
    for (const [spriteId, previousAnimation] of this
      .generationAnimationSnapshots) {
      if (previousAnimation) {
        animations[spriteId] = {
          ...previousAnimation,
          lastFrameTime: previousAnimation.playing
            ? undefined
            : previousAnimation.lastFrameTime,
        };
      } else {
        delete animations[spriteId];
      }
    }
    this.generationAnimationSnapshots.clear();
    this.state = {...this.state, animations};
  }

  private resolvePredictionSource(sourceSelector: string) {
    if (!sourceSelector.startsWith('class:')) {
      const source = this.getElement(sourceSelector);
      return source?.kind === 'sprite' ? source : undefined;
    }

    const touchedSprite = this.activeTouchTargetId
      ? this.getElement(this.activeTouchTargetId)
      : undefined;
    const className = sourceSelector.slice(6);
    return touchedSprite?.kind === 'sprite' &&
      touchedSprite.className?.trim() === className
      ? touchedSprite
      : undefined;
  }

  private isSprite(elementId: string) {
    return this.getElement(elementId)?.kind === 'sprite';
  }

  private predictionTarget(request: PendingPrediction) {
    return request.kind === 'element'
      ? request.resultElementId
      : request.predictorSpriteId;
  }

  private isLatestPrediction(request: PendingPrediction) {
    return (
      this.latestPredictionRequests.get(this.predictionTarget(request)) ===
      request.requestId
    );
  }

  private queuePrediction(request: PendingPrediction, targetId: string) {
    this.pendingPredictions.push(request);
    this.latestPredictionRequests.set(targetId, request.requestId);
    this.state = {...this.state, pendingPrediction: request};
  }

  private setSpritePredictionFailure(spriteId: string, message: string) {
    this.setSpriteData(spriteId, SPRITE_PREDICTION_DATA_KEYS.status, 'failed');
    this.setSpriteData(spriteId, SPRITE_PREDICTION_DATA_KEYS.error, message);
    for (const handler of [
      ...(this.predictionFailedHandlers.get(spriteId) ?? []),
    ]) {
      handler();
    }
    if (!this.activeTouchTargetId) {
      this.checkTouchEvents();
    }
  }

  private refreshVariableBindings(variableName: string) {
    const value = this.state.variables[variableName] ?? '';
    for (const [elementId, boundVariableName] of this.variableBindings) {
      if (boundVariableName === variableName) {
        this.updateElementText(elementId, value);
      }
    }
  }

  private updateElementText(elementId: string, text: string) {
    this.state = {
      ...this.state,
      elements: this.state.elements.map(element =>
        element.id === elementId ? {...element, label: text} : element
      ),
    };
  }

  private checkTouchEvents() {
    const activeTouchPairs = new Set<string>();
    for (const [key, registration] of this.touchHandlers) {
      const first = this.state.elements.find(
        element => element.id === registration.firstId
      );
      if (!first || first.screenId !== this.state.screenId) {
        continue;
      }

      const targets = registration.targetSelector.startsWith('class:')
        ? this.state.elements.filter(
            element =>
              element.kind === 'sprite' &&
              element.className?.trim() ===
                registration.targetSelector.slice(6) &&
              element.screenId === this.state.screenId
          )
        : this.state.elements.filter(
            element =>
              element.id === registration.targetSelector &&
              element.screenId === this.state.screenId
          );

      for (const target of targets) {
        const pairKey = `${key}|${target.id}`;
        if (
          !spritesAreTouching(
            this.state.elements,
            registration.firstId,
            target.id
          )
        ) {
          continue;
        }

        activeTouchPairs.add(pairKey);
        if (!this.activeTouchPairs.has(pairKey)) {
          for (const handler of [...registration.handlers]) {
            const previousTouchTargetId = this.activeTouchTargetId;
            this.activeTouchTargetId = target.id;
            try {
              handler();
            } finally {
              this.activeTouchTargetId = previousTouchTargetId;
            }
          }
        }
      }
    }
    this.activeTouchPairs = activeTouchPairs;
  }

  private executeGeneratedProgram(source: string) {
    if (!source.trim()) {
      return;
    }

    // This function executes code generated from registered Blockly blocks,
    // not arbitrary source entered by the user. The engine API is the only
    // object exposed to the generated program.
    const program = new Function('engine', `'use strict';\n${source}`) as (
      engine: BuildLabEngine
    ) => void;
    program(this);
  }
}

function cloneRuntimeState(state: RuntimeState): RuntimeState {
  return {
    ...state,
    animations: state.animations
      ? Object.fromEntries(
          Object.entries(state.animations).map(([spriteId, animation]) => [
            spriteId,
            {...animation},
          ])
        )
      : undefined,
    elements: state.elements.map(element => ({
      ...element,
      data: element.data ? {...element.data} : undefined,
    })),
    variables: {...state.variables},
    keyboardMovements: state.keyboardMovements?.map(movement => ({
      ...movement,
    })),
  };
}

function snapCoordinate(value: number, extent = DEFAULT_SPRITE_SIZE) {
  const safeValue = Number.isFinite(value) ? value : STAGE_SIZE / 2;
  return clampToStage(Math.round(safeValue / GRID_SIZE) * GRID_SIZE, extent);
}
