import {Output} from 'ai';
import z from 'zod/v3';

import {generateText} from '@cdo/apps/aiGateway';

import {SlidesPageContext} from '../../curriculum-generator/ai/context';
import {
  getTextModel,
  logPrompt,
  logResponse,
  PROMPT_TAGS,
} from '../../curriculum-generator/ai/shared';

// Bounds on the deck the outline AI is allowed to plan. Quoted both in
// the prompt and in the zod schema so the limits stay in sync.
const MIN_SLIDES = 1;
const MAX_SLIDES = 20;
const DEFAULT_SLIDES_HINT = '3-6';

const slidesOutlineSchema = Output.object({
  schema: z.object({
    slides: z
      .array(
        z.object({
          description: z
            .string()
            .describe(
              'A meta-description, in the curriculum author\'s voice, of what this slide will cover. Written so the levelbuilder can scan the card list and decide whether each slide belongs, NOT written as if the student were reading it. Use the imperative or third-person — "Introduce X." / "Show a contrast between Y and Z." / "Set up the question the lesson answers." — never second-person student narration. The actual student-facing panel text is generated by a downstream AI call from this description; don\'t pre-write it here, and don\'t describe a specific image.'
            ),
        })
      )
      .min(MIN_SLIDES)
      .max(MAX_SLIDES),
  }),
});

export interface OutlineSlide {
  description: string;
}

// Given the slides-page context (lesson identity, optional deck-level
// outline, formatted lesson level content, and inherited unit/lesson
// outline fields), ask the model for a sequence of slide descriptions
// to show students BEFORE the lesson.
//
// The slides should set up context for the lesson without giving away
// the work. Concretely: introduce the topic and stakes, motivate why
// this matters, mention the technique or concept the student is about
// to use, but stop short of walking through the solution.
export async function generateSlidesOutline(
  ctx: SlidesPageContext
): Promise<OutlineSlide[]> {
  const prompt = [
    'You are helping a curriculum author plan a sequence of intro slides',
    'shown to students BEFORE they begin a CS lesson. The slides set up',
    'context — what the lesson is about, why it matters, and what concept',
    'or technique the students are about to practice. They must NOT walk',
    'through the solution to any level; they should leave students with',
    'curiosity and enough framing to engage productively.',
    '',
    'Each slide will be implemented as a single Panels-app panel (one',
    `16:9 illustration + text overlay). Plan ${MIN_SLIDES} to ${MAX_SLIDES} slides; default`,
    `to ${DEFAULT_SLIDES_HINT} unless the outline below asks for more.`,
    '',
    'Audience and tone: the unit may be aimed at any grade range, from',
    'elementary to high school or beyond. Read the outlines below for',
    "the levelbuilder's intent and match them. If no outline is provided,",
    'infer the level from the lesson content; do not assume any',
    'specific grade.',
    '',
    `Lesson: ${ctx.lessonName}`,
    '',
    ...(ctx.unitOutline
      ? [
          `Unit context — this lesson sits inside the unit "${
            ctx.unitName ?? ''
          }". Use it for broad framing (audience, arc, recurring themes)`,
          'but the deck itself is about the specific lesson below:',
          ctx.unitOutline,
          '',
        ]
      : []),
    ...(ctx.lessonOutline
      ? [
          'Lesson outline (the levelbuilder typed this when planning the',
          "lesson's own levels — match its tone and the concepts it names",
          'when framing the intro deck):',
          ctx.lessonOutline,
          '',
        ]
      : []),
    ...(ctx.slidesOutline
      ? [
          'Slides outline (the levelbuilder typed this specifically for',
          'this deck; match its audience, depth, vocabulary, and tone —',
          'do not soften technical content if the outline asks for it):',
          ctx.slidesOutline,
          '',
        ]
      : []),
    ...(ctx.levelContents
      ? [
          'Lesson level content (the existing generated levels of this',
          'lesson, in order). Use these to understand what the student',
          'is about to do so the slides can set the stage without',
          'spoiling solutions:',
          ctx.levelContents,
          '',
        ]
      : []),
    'IMPORTANT — what each `description` should look like:',
    "Write each description in the curriculum author's voice, as a brief",
    'plan for the slide. The levelbuilder will scan a list of these on a',
    'page and decide whether each slide belongs; they are NOT what the',
    'student will read. The actual student-facing panel text is generated',
    'by a downstream AI call from this description — leave that to it.',
    '',
    'Good description shape:',
    '  - "Introduce why HTML structure matters; set up the contrast',
    '     between unstructured text and well-organized markup. Mention',
    '     the tags the lesson will cover: <h1>, <p>, <ul>."',
    '  - "Show what happens without alt text on an image. Set up the',
    '     accessibility motivation for the <img> attributes coming up."',
    '',
    'Bad description shape (do NOT do this — these read like the slide',
    'itself, not a plan for it):',
    '  - "Imagine a webpage with just plain text — no pictures, no...”',
    '  - "Have you ever wondered how websites organize their content?"',
    '',
    'Use imperative ("Introduce…", "Show…", "Frame…") or third-person',
    '("The slide presents…"). Never second-person student narration',
    '("you", "imagine", "have you ever"). 2-5 sentences. Name specific',
    'syntax or terminology you want carried into the slide text.',
  ].join('\n');

  const context = {level: ctx.lessonName, subtask: 'slides-outline'};
  logPrompt(PROMPT_TAGS.SLIDES_OUTLINE, prompt, context);
  const response = await generateText({
    model: getTextModel(),
    prompt,
    output: slidesOutlineSchema,
  });
  const slides = (response.output as {slides: OutlineSlide[]}).slides;
  logResponse(PROMPT_TAGS.SLIDES_OUTLINE, slides, context);
  if (!slides?.length) {
    throw new Error('Model returned no slides');
  }
  return slides;
}
