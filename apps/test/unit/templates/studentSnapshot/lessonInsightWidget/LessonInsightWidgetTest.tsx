import '@testing-library/jest-dom';
import {act, render, screen, waitFor} from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import React from 'react';
import {Provider} from 'react-redux';
import {createStore, combineReducers} from 'redux';

import LessonInsightWidget from '@cdo/apps/templates/studentSnapshot/lessonInsightWidget';
import HttpClient from '@cdo/apps/util/HttpClient';

jest.mock('@cdo/apps/util/HttpClient');
const mockHttpClient = HttpClient as jest.Mocked<typeof HttpClient>;

describe('LessonInsightWidget', () => {
  const defaultProps = {
    selectedUnitId: 1,
    selectedLessonId: 2,
    selectedStudentId: 3,
  };

  const mockInsightData = {
    progress: 'Student has made good progress',
    misconceptions: 'No major misconceptions found',
    assessment: 'Assessment shows understanding',
    next_steps: 'Continue with next lesson',
  };

  const mockStore = createStore(
    combineReducers({
      teacherSections: (
        state = {
          selectedSectionId: 123,
          sections: {
            123: {courseId: 1, unitPosition: 1},
          },
          selectedStudents: [],
        }
      ) => state,
    })
  );

  const renderComponent = (props = {}) => {
    return render(
      <Provider store={mockStore}>
        <LessonInsightWidget {...defaultProps} {...props} />
      </Provider>
    );
  };

  beforeEach(() => {
    jest.clearAllMocks();
    const defaultMockResponse = {
      value: {
        json: JSON.stringify(mockInsightData),
      },
      response: new Response(),
    };
    mockHttpClient.fetchJson.mockResolvedValue(defaultMockResponse);
  });

  it('renders the widget with correct title', () => {
    renderComponent();
    expect(screen.getByText('Lesson Insight')).toBeInTheDocument();
  });

  it('displays loading state initially', () => {
    renderComponent();
    expect(screen.getByText('Lesson Insight')).toBeInTheDocument();
  });

  it('fetches and displays insight data when parameters are provided', async () => {
    const mockResponse = {
      value: {
        json: JSON.stringify(mockInsightData),
      },
      response: new Response(),
    };

    mockHttpClient.fetchJson.mockResolvedValue(mockResponse);

    renderComponent();

    await waitFor(() => {
      expect(mockHttpClient.fetchJson).toHaveBeenCalledWith(
        '/student_snapshots/lesson_insight?lesson_id=2&unit_id=1&student_id=3&section_id=123'
      );
    });

    await waitFor(() => {
      expect(screen.getByText('Progress')).toBeInTheDocument();
      expect(
        screen.getByText('Student has made good progress')
      ).toBeInTheDocument();
      expect(screen.getByText('Misconceptions')).toBeInTheDocument();
      expect(
        screen.getByText('No major misconceptions found')
      ).toBeInTheDocument();
      expect(screen.getByText('Assessment')).toBeInTheDocument();
      expect(
        screen.getByText('Assessment shows understanding')
      ).toBeInTheDocument();
      expect(screen.getByText('Next Steps')).toBeInTheDocument();
      expect(screen.getByText('Continue with next lesson')).toBeInTheDocument();
      expect(
        screen.getByText('Generated by AI Teaching Assistant')
      ).toBeInTheDocument();
    });
  });

  it('does not fetch data when required parameters are missing', () => {
    mockHttpClient.fetchJson.mockClear();

    renderComponent({selectedUnitId: null});

    expect(mockHttpClient.fetchJson).not.toHaveBeenCalled();
  });

  it('displays error message when fetch fails', async () => {
    const mockError = new Error('Network error');
    mockHttpClient.fetchJson.mockRejectedValue(mockError);

    renderComponent();

    await waitFor(() => {
      expect(
        screen.getByText('Failed to fetch insight data')
      ).toBeInTheDocument();
    });
  });

  it('displays error message when JSON parsing fails', async () => {
    const mockResponse = {
      value: {
        json: 'invalid json',
      },
      response: new Response(),
    };

    mockHttpClient.fetchJson.mockResolvedValue(mockResponse);

    renderComponent();

    await waitFor(() => {
      expect(
        screen.getByText('Failed to parse insight data')
      ).toBeInTheDocument();
    });
  });

  it('allows refreshing insight data via settings menu', async () => {
    const mockResponse = {
      value: {
        json: JSON.stringify(mockInsightData),
      },
      response: new Response(),
    };

    mockHttpClient.fetchJson.mockResolvedValue(mockResponse);

    renderComponent();

    await waitFor(() => {
      expect(mockHttpClient.fetchJson).toHaveBeenCalledTimes(1);
    });

    const refreshButton = screen.queryByLabelText('Refresh Insight');
    if (refreshButton) {
      await act(async () => {
        await userEvent.click(refreshButton);
      });

      await waitFor(() => {
        expect(mockHttpClient.fetchJson).toHaveBeenCalledTimes(2);
      });
    }
  });
});
