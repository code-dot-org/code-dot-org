// The one seam everything else in this package is built around.
//
// In the legacy bundle this is an `if`: `submitChatContents` asks
// `shouldUseAiGateway(modelId)` and calls either `performClientApiChatCompletion`
// (the `ai` SDK, client-side, Turnstile-gated) or `postAichatCompletionMessage`
// (Rails). Both arms read studio redux directly — `state.progress`, `state.lab`,
// `state.lab2Project`, the section access level, the view-as user — which is
// exactly what a package cannot do.
//
// So the branch becomes an object, and everything studio-shaped moves into the
// request, put there by the host. The payoff is not tidiness: it is that a
// fixture and a developer's own API key are two more implementations of one
// method rather than two more arms of an `if` inside a thunk (specs/PLAN.md §5).

import type {CompletedMessage, PendingMessage} from '../model/messages';

/**
 * What the host knows and the package does not.
 *
 * Opaque here, and deliberately so: the fixture transport ignores every field,
 * the dashboard transport needs most of them, and the package itself needs
 * none. Every one of these is a redux selector in the legacy send path.
 */
export interface TutorSessionInfo {
  levelId?: number;
  scriptId?: number;
  channelId?: string;
  lessonId?: number;
  /** Which product is asking — the tutor, or the lesson deep dive. */
  clientType?: string;
  /**
   * Which model, as a bare string.
   *
   * Legacy pins this to `AiChatModelIds` from `generated-scripts/sharedConstants`,
   * generated by Rails and unavailable here. A transport that cares knows the
   * vocabulary it accepts; one that does not, ignores it.
   */
  modelId?: string;
}

export interface TutorRequest {
  /** What the student typed. */
  message: PendingMessage;

  /**
   * Prior turns, oldest first.
   *
   * Already filtered to `OK` by the caller, because a failed turn is a thing the
   * student saw and not a thing the model said — sending it back would teach the
   * model that its own errors are part of the conversation.
   */
  history: readonly CompletedMessage[];

  /** Project context, assembled by the host (specs/PLAN.md §3). */
  hiddenContext?: string;

  systemPrompt?: string;

  /**
   * A JSON Schema, when this session wants files back rather than prose.
   *
   * Its presence is what makes `TutorReply.structuredOutput` meaningful; see
   * specs/PLAN.md §8.
   */
  responseSchema?: object;

  session: TutorSessionInfo;
}

export interface TutorReply {
  /**
   * The user's turn, echoed with an id and a settled status, then the
   * assistant's — which is absent when the user's turn itself failed, because
   * in that case the model was never called.
   */
  messages: CompletedMessage[];

  /** The parsed reply, when the request carried a `responseSchema`. */
  structuredOutput?: unknown;
}

export interface TutorTransport {
  /**
   * Answer one turn.
   *
   * Rejects only when the request could not be completed AT ALL — a network
   * failure, an abort. A turn that failed in a way the model or the server can
   * describe comes back as a resolved reply whose messages carry the failing
   * status, because that is a thing the panel renders rather than an exception
   * it catches.
   */
  complete(request: TutorRequest, signal?: AbortSignal): Promise<TutorReply>;
}
