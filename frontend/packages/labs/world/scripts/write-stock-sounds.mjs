// Writes the stock sound manifest into the lab's source.
//
// Names only. The bytes are not here and never will be: a sound is fetched by
// `yarn setup:world` into `public/sounds/` and served (specs/SOUND.md), the
// same arrangement the backdrops have and for the same reason — 39 mp3s is
// several megabytes, and a bundle is not a shelf. What the lab needs in the
// bundle is the LIST, because the library dialog has to know what is on the
// shelf before it asks for any of it.
//
// So this reads `sounds.txt` and nothing else. It needs no network: re-run it
// when `sounds.txt` changes.
//
//   node scripts/write-stock-sounds.mjs

import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';

import {soundEntries} from './stockSoundNames.mjs';

const here = fileURLToPath(new URL('.', import.meta.url));
const listing = join(here, '../sounds.txt');
const out = join(here, '../src/sound/stockSounds.ts');

const ids = soundEntries(readFileSync(listing, 'utf8')).map(entry => entry.id);

const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index);
if (duplicates.length) {
  // Two entries whose names collide would overwrite each other in
  // public/sounds/, leaving the shelf listing a sound nobody can hear.
  throw new Error(`duplicate sound names: ${duplicates.join(', ')}`);
}

// An id becomes a file name, a block's stored value and (quoted below) source
// code, so anything outside this alphabet is a name `sounds.txt` should spell
// differently rather than something to pass through and find out about later.
const odd = ids.filter(id => !/^[a-z][a-zA-Z0-9]*$/.test(id));
if (odd.length) {
  throw new Error(`sound names are not plain identifiers: ${odd.join(', ')}`);
}

writeFileSync(
  out,
  [
    '// GENERATED by scripts/write-stock-sounds.mjs — do not edit.',
    '//',
    '// The stock sounds on the shelf, by id. The bytes are NOT here: they are',
    '// fetched by `yarn setup:world` from the URLs in sounds.txt and served',
    '// from the sound base URL (runtime/worldConfig), which is what the library',
    '// dialog fetches when a learner imports one. See specs/SOUND.md.',
    '',
    "/** Every stock sound's id — `coin` is served as `coin.mp3`. */",
    'export const STOCK_SOUND_IDS: readonly string[] = [',
    ...ids.map(id => `  '${id}',`),
    '];',
    '',
  ].join('\n'),
);

console.log(
  `stock sounds: wrote ${ids.length} names to src/sound/stockSounds.ts`,
);
