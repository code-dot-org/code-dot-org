// Writes the stock appearance images into the lab's source as data URLs.
//
// A World project owns every image it draws: importing a stock sprite copies the
// PNG into the project, and from then on it is the learner's file — repaintable,
// renamable, deletable. So the bytes have to be somewhere the lab can hand out
// at import time, which is here rather than a URL the runtime fetches.
//
// Generated, and committed: the drawings live in `generate-sprites.mjs` (pure
// Node, no image dependency), and this is their base64. Re-run after editing a
// drawing:  node scripts/write-stock-assets.mjs

import {writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';

import {stockImages} from './generate-sprites.mjs';

const here = fileURLToPath(new URL('.', import.meta.url));
const out = join(here, '../src/appearance/stockImages.ts');

const images = stockImages();
const entries = Object.entries(images)
  .map(
    ([name, png]) =>
      `  ${JSON.stringify(name)}:\n    'data:image/png;base64,${png.toString('base64')}',`,
  )
  .join('\n');

writeFileSync(
  out,
  `// GENERATED by scripts/write-stock-assets.mjs — do not edit.
//
// The stock appearance images, as data URLs. An import copies one of these into
// the project as a file of its own; nothing here is loaded at runtime unless a
// project holds a copy of it. The drawings are in scripts/generate-sprites.mjs.

/** Stock images by name, each a \`data:image/png;base64,…\` URL. */
export const STOCK_IMAGES: Record<string, string> = {
${entries}
};
`,
);

console.log(
  `stock assets: wrote ${Object.keys(images).length} images to src/appearance/stockImages.ts`,
);
