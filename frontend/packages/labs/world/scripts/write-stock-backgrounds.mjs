// Writes the stock backdrop manifest into the lab's source.
//
// Names only. The bytes are not here and never will be: a backdrop is fetched
// by `yarn setup:world` into `public/backgrounds/` and served (BACKGROUNDS.md
// §7), unlike a stock sprite, whose base64 is committed in `stockImages.ts`.
// What the lab still needs in the bundle is the LIST — the library dialog has to
// know what is on the shelf before it asks for any of it.
//
// So this reads `backgrounds.txt` and nothing else. The names it writes are
// derived from the same URLs the downloader derives its file names from, by the
// same function, which is what keeps a shelf entry and a downloaded file from
// disagreeing about what something is called. It needs no network and no image:
// re-run it when `backgrounds.txt` changes.
//
//   node scripts/write-stock-backgrounds.mjs

import {readFileSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';

import {backgroundUrls, backgroundFileName} from './stockBackgroundNames.mjs';

const here = fileURLToPath(new URL('.', import.meta.url));
const listing = join(here, '../backgrounds.txt');
const out = join(here, '../src/appearance/stockBackgrounds.ts');

const ids = backgroundUrls(readFileSync(listing, 'utf8')).map(url =>
  backgroundFileName(url).replace(/\.png$/, ''),
);

const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index);
if (duplicates.length) {
  // Two URLs whose names collide would overwrite each other in
  // public/backgrounds/, leaving the shelf listing a backdrop nobody can see.
  throw new Error(`duplicate backdrop names: ${duplicates.join(', ')}`);
}

// An id becomes a file name, a block's stored value and (quoted below) source
// code, so anything outside this alphabet is a URL this script should be taught
// to name rather than something to pass through and find out about later.
const odd = ids.filter(id => !/^[a-z][a-zA-Z0-9]*$/.test(id));
if (odd.length) {
  throw new Error(
    `backdrop names are not plain identifiers: ${odd.join(', ')}`,
  );
}

writeFileSync(
  out,
  `// GENERATED by scripts/write-stock-backgrounds.mjs — do not edit.
//
// The stock backdrops on the shelf, by id. The bytes are NOT here: they are
// fetched by \`yarn setup:world\` from the URLs in backgrounds.txt and served
// from the background base URL (runtime/worldConfig), which is what the library
// dialog fetches when a learner imports one. See specs/BACKGROUNDS.md §7.

/** Every stock backdrop's id — \`cave\` is served as \`cave.png\`. */
export const STOCK_BACKGROUND_IDS: readonly string[] = [
${ids.map(id => `  '${id}',`).join('\n')}
];
`,
);

console.log(
  `stock backdrops: wrote ${ids.length} names to src/appearance/stockBackgrounds.ts`,
);
